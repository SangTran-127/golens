import Foundation
import Observation

@Observable
public final class GeneratedFileOriginCache: @unchecked Sendable {
    public private(set) var origins: [String: GeneratedFileOriginResult?] = [:]
    @ObservationIgnored public var versions: [String: Int] = [:]

    public init() {}

    public func origin(for path: String) -> GeneratedFileOriginResult? {
        guard path.hasSuffix(".go"), !path.isEmpty else { return nil }
        if let cached = origins[path] {
            return cached
        }
        return nil
    }

    public func hasCachedVersion(_ version: Int, for path: String) -> Bool {
        versions[path] == version && origins.keys.contains(path)
    }

    @discardableResult
    public func store(_ value: GeneratedFileOriginResult?, for path: String, version: Int) -> Bool {
        versions[path] = version
        if case let .some(existing) = origins[path], existing == value {
            return false
        }
        origins.updateValue(value, forKey: path)
        return true
    }

    @discardableResult
    public func remove(for path: String) -> Bool {
        versions.removeValue(forKey: path)
        guard origins.keys.contains(path) else { return false }
        origins.removeValue(forKey: path)
        return true
    }

    @discardableResult
    public func clear() -> Bool {
        versions.removeAll()
        guard !origins.isEmpty else { return false }
        origins.removeAll()
        return true
    }

    public func refreshImmediately(
        for path: String,
        text: String,
        version: Int,
        syncsToCore: Bool = true,
        workspaceRoot: String = "",
        readFile: (String) -> String? = { try? String(contentsOfFile: $0, encoding: .utf8) },
        listDirectory: (String) -> [String] = { (try? FileManager.default.contentsOfDirectory(atPath: $0)) ?? [] },
        fileExists: (String) -> Bool = { FileManager.default.fileExists(atPath: $0) }
    ) {
        guard path.hasSuffix(".go"), !path.isEmpty else {
            _ = remove(for: path)
            return
        }
        if !syncsToCore {
            _ = store(nil, for: path, version: version)
            return
        }
        if hasCachedVersion(version, for: path) {
            return
        }
        guard GeneratedFileOrigin.parseHeader(text) != nil else {
            _ = store(nil, for: path, version: version)
            return
        }
        let resolved = GeneratedFileOrigin.resolve(
            content: text,
            goFilePath: path,
            workspaceRoot: workspaceRoot,
            readFile: readFile,
            listDirectory: listDirectory,
            fileExists: fileExists
        )
        _ = store(resolved, for: path, version: version)
    }
}

public struct GoGenerateDirectiveMatch: Equatable, Sendable {
    public let filePath: String
    public let line: Int
    public let command: String

    public init(filePath: String, line: Int, command: String) {
        self.filePath = filePath
        self.line = line
        self.command = command
    }
}

public struct GeneratedFileOriginResult: Equatable, Sendable {
    public let generator: String
    public let headerLine: String
    public let sourcePath: String?
    public let sourceDisplayName: String?
    public let defaultLine: Int
    public let generateDirective: GoGenerateDirectiveMatch?

    public init(
        generator: String,
        headerLine: String,
        sourcePath: String?,
        sourceDisplayName: String?,
        defaultLine: Int,
        generateDirective: GoGenerateDirectiveMatch?
    ) {
        self.generator = generator
        self.headerLine = headerLine
        self.sourcePath = sourcePath
        self.sourceDisplayName = sourceDisplayName
        self.defaultLine = defaultLine
        self.generateDirective = generateDirective
    }
}

public enum GeneratedFileOrigin {
    private static let knownGenerators: [(needle: String, canonical: String)] = [
        ("protoc-gen-go-grpc", "protoc-gen-go-grpc"),
        ("protoc-gen-go", "protoc-gen-go"),
        ("mockgen", "mockgen"),
        ("stringer", "stringer"),
        ("oapi-codegen", "oapi-codegen"),
        ("go:generate go run -mod=mod entgo.io/ent", "ent"),
        ("generated by ent", "ent"),
        ("entgo.io/ent", "ent"),
        ("generated by wire", "wire"),
        ("google/wire", "wire"),
        ("generated by sqlc", "sqlc")
    ]

    public static func parseHeader(_ content: String) -> (generator: String, headerLine: String)? {
        let lines = content.split(separator: "\n", maxSplits: 45, omittingEmptySubsequences: false)
        let previewLimit = min(40, lines.count)
        var detectedHeader: String?
        var commentLines: [String] = []

        for idx in 0..<previewLimit {
            let line = lines[idx].trimmingCharacters(in: CharacterSet(charactersIn: "\r"))
            if line.hasPrefix("//") {
                commentLines.append(line)
            }
            if detectedHeader == nil, isCodeGeneratedMarker(line) {
                detectedHeader = line
            }
        }

        guard let header = detectedHeader else { return nil }
        let block = commentLines.joined(separator: "\n")
        let generator = identifyGenerator(header: header, commentBlock: block)
        return (generator, header)
    }

    public static func isCodeGeneratedMarker(_ line: String) -> Bool {
        let trimmed = line.trimmingCharacters(in: .whitespaces)
        guard trimmed.hasPrefix("// Code generated "),
              trimmed.hasSuffix("DO NOT EDIT.") || trimmed.hasSuffix("DO NOT EDIT") else {
            return false
        }
        return true
    }

    public static func mappedOriginLocation(
        in content: String,
        forGeneratedLine line1Based: Int,
        goFilePath: String,
        workspaceRoot: String = "",
        fileExists: (String) -> Bool = { FileManager.default.fileExists(atPath: $0) }
    ) -> (path: String, line: Int)? {
        guard line1Based >= 1 else { return nil }
        let rawLines = content.split(separator: "\n", omittingEmptySubsequences: false)
        let upper = min(line1Based, rawLines.count)
        guard upper >= 1 else { return nil }

        let goDir = (goFilePath as NSString).deletingLastPathComponent
        var idx = upper - 1
        while idx >= 0 {
            let raw = rawLines[idx].trimmingCharacters(in: CharacterSet(charactersIn: "\r"))
            if let directive = parseLineDirective(raw) {
                let directiveLine1Based = idx + 1
                let delta = max(0, line1Based - (directiveLine1Based + 1))
                let mappedLine = max(1, directive.line + delta)
                let resolved = resolveCandidatePath(
                    directive.path,
                    goDir: goDir,
                    workspaceRoot: workspaceRoot,
                    fileExists: fileExists
                ) ?? normalizeJoinedPath(base: goDir, relative: directive.path)
                return (resolved, mappedLine)
            }
            idx -= 1
        }
        return nil
    }

    public static func resolve(
        content: String,
        goFilePath: String,
        workspaceRoot: String = "",
        readFile: (String) -> String? = { try? String(contentsOfFile: $0, encoding: .utf8) },
        listDirectory: (String) -> [String] = { (try? FileManager.default.contentsOfDirectory(atPath: $0)) ?? [] },
        fileExists: (String) -> Bool = { FileManager.default.fileExists(atPath: $0) }
    ) -> GeneratedFileOriginResult? {
        guard !goFilePath.isEmpty, let headerInfo = parseHeader(content) else { return nil }

        let goDir = (goFilePath as NSString).deletingLastPathComponent
        let fileName = (goFilePath as NSString).lastPathComponent
        let previewLines = content
            .split(separator: "\n", maxSplits: 45, omittingEmptySubsequences: false)
            .prefix(40)
            .map { $0.trimmingCharacters(in: CharacterSet(charactersIn: "\r")) }

        let directives = collectGenerateDirectives(
            inDirectory: goDir,
            excludingFile: goFilePath,
            workspaceRoot: workspaceRoot,
            listDirectory: listDirectory,
            readFile: readFile
        )
        let matchedDirective = pickMatchingDirective(
            generator: headerInfo.generator,
            generatedFileName: fileName,
            headerLine: headerInfo.headerLine,
            candidates: directives
        )

        var resolvedSource: String? = nil
        var defaultLine = 1

        if let hint = extractCommentSourceHint(from: previewLines) {
            resolvedSource = resolveCandidatePath(
                hint,
                goDir: goDir,
                workspaceRoot: workspaceRoot,
                fileExists: fileExists
            )
            if resolvedSource == nil && (hint.contains("/") || hint.contains(".")) {
                resolvedSource = normalizeJoinedPath(base: goDir, relative: hint)
            }
        }

        if resolvedSource == nil, headerInfo.generator == "stringer" {
            let typeName = extractFlagValue("-type", from: headerInfo.headerLine)
                ?? extractFlagValue("-type", from: matchedDirective?.command ?? "")
                ?? inferredStringerTypeName(fromFileName: fileName)
            if let typeName, let match = findTypeDeclaration(
                named: typeName,
                inDirectory: goDir,
                excludingFile: goFilePath,
                listDirectory: listDirectory,
                readFile: readFile
            ) {
                resolvedSource = match.path
                defaultLine = match.line
            }
        }

        if resolvedSource == nil, headerInfo.generator == "mockgen" {
            if let sourceFlag = extractFlagValue("-source", from: headerInfo.headerLine)
                ?? extractFlagValue("-source", from: matchedDirective?.command ?? "") {
                resolvedSource = resolveCandidatePath(
                    sourceFlag,
                    goDir: goDir,
                    workspaceRoot: workspaceRoot,
                    fileExists: fileExists
                ) ?? normalizeJoinedPath(base: goDir, relative: sourceFlag)
            } else if let ifaceName = inferredMockgenInterfaceName(in: content) {
                let searchDirs = uniqueNonEmpty([goDir, matchedDirective.map { ($0.filePath as NSString).deletingLastPathComponent }])
                for dir in searchDirs {
                    if let match = findInterfaceDeclaration(
                        named: ifaceName,
                        inDirectory: dir,
                        excludingFile: goFilePath,
                        listDirectory: listDirectory,
                        readFile: readFile
                    ) {
                        resolvedSource = match.path
                        defaultLine = match.line
                        break
                    }
                }
            }
        }

        if resolvedSource == nil, headerInfo.generator == "protoc-gen-go" || headerInfo.generator == "protoc-gen-go-grpc" {
            let stem: String
            if fileName.hasSuffix("_grpc.pb.go") {
                stem = String(fileName.dropLast("_grpc.pb.go".count))
            } else if fileName.hasSuffix(".pb.go") {
                stem = String(fileName.dropLast(".pb.go".count))
            } else {
                stem = (fileName as NSString).deletingPathExtension
            }
            if !stem.isEmpty {
                resolvedSource = searchAncestorAndSubdirs(
                    named: "\(stem).proto",
                    subdirs: ["proto", "protos", "api", "idl"],
                    startDir: goDir,
                    workspaceRoot: workspaceRoot,
                    fileExists: fileExists
                )
            }
        }

        if resolvedSource == nil, headerInfo.generator == "wire" {
            let candidate = (goDir as NSString).appendingPathComponent("wire.go")
            if fileExists(candidate) {
                resolvedSource = candidate
            }
        }

        if resolvedSource == nil, headerInfo.generator == "oapi-codegen" {
            if let cmd = matchedDirective?.command, let spec = extractOapiSpecArg(from: cmd) {
                let base = matchedDirective.map { ($0.filePath as NSString).deletingLastPathComponent } ?? goDir
                resolvedSource = resolveCandidatePath(spec, goDir: base, workspaceRoot: workspaceRoot, fileExists: fileExists)
                    ?? normalizeJoinedPath(base: base, relative: spec)
            }
            if resolvedSource == nil {
                for name in ["openapi.yaml", "openapi.yml", "openapi.json", "api.yaml", "api.yml", "swagger.yaml"] {
                    if let hit = searchAncestorAndSubdirs(
                        named: name,
                        subdirs: ["api", "openapi", "spec", "specs"],
                        startDir: goDir,
                        workspaceRoot: workspaceRoot,
                        fileExists: fileExists
                    ) {
                        resolvedSource = hit
                        break
                    }
                }
            }
        }

        if resolvedSource == nil, headerInfo.generator == "ent" {
            let stem = (fileName as NSString).deletingPathExtension
            let schemaName = "\(stem.lowercased()).go"
            let schemaDir = searchAncestorNamedDirectory("schema", startDir: goDir, workspaceRoot: workspaceRoot, fileExists: fileExists)
            if let schemaDir {
                let candidate = (schemaDir as NSString).appendingPathComponent(schemaName)
                if fileExists(candidate) {
                    resolvedSource = candidate
                }
            }
            if resolvedSource == nil {
                let fallback = normalizeJoinedPath(base: goDir, relative: "schema/\(schemaName)")
                if fileExists(fallback) {
                    resolvedSource = fallback
                } else {
                    let parentFallback = normalizeJoinedPath(base: (goDir as NSString).deletingLastPathComponent, relative: "schema/\(schemaName)")
                    if fileExists(parentFallback) {
                        resolvedSource = parentFallback
                    }
                }
            }
        }

        if resolvedSource == nil, headerInfo.generator == "sqlc" {
            if let sqlcConfig = findSqlcConfig(startDir: goDir, workspaceRoot: workspaceRoot, fileExists: fileExists) {
                resolvedSource = sqlcConfig
            }
        }

        if resolvedSource == nil, let firstLineDirective = firstLineDirectiveLocation(in: content, goDir: goDir, workspaceRoot: workspaceRoot, fileExists: fileExists) {
            let directiveFileName = (firstLineDirective.path as NSString).lastPathComponent
            if directiveFileName != fileName {
                resolvedSource = firstLineDirective.path
                defaultLine = firstLineDirective.line
            }
        }

        if resolvedSource == nil, let matchedDirective {
            resolvedSource = matchedDirective.filePath
            defaultLine = matchedDirective.line
        }

        let displayName = resolvedSource.map { displayPath(for: $0, workspaceRoot: workspaceRoot) }
        return GeneratedFileOriginResult(
            generator: headerInfo.generator,
            headerLine: headerInfo.headerLine,
            sourcePath: resolvedSource,
            sourceDisplayName: displayName,
            defaultLine: defaultLine,
            generateDirective: matchedDirective
        )
    }

    private static func identifyGenerator(header: String, commentBlock: String) -> String {
        let lowerHeader = header.lowercased()
        let lowerBlock = commentBlock.lowercased()
        for entry in knownGenerators {
            if lowerHeader.contains(entry.needle) || lowerBlock.contains(entry.needle) {
                return entry.canonical
            }
        }
        if let byRange = header.range(of: "Code generated by ") {
            var tail = String(header[byRange.upperBound...])
            if let stop = tail.range(of: "DO NOT EDIT") {
                tail = String(tail[..<stop.lowerBound])
            }
            let cleaned = tail.trimmingCharacters(in: CharacterSet(charactersIn: " \t\"';.,:-"))
            if !cleaned.isEmpty {
                let firstWord = cleaned.split(whereSeparator: { $0 == " " || $0 == "\t" }).first.map(String.init) ?? cleaned
                let trimmedWord = firstWord.trimmingCharacters(in: CharacterSet(charactersIn: "\"';.,:-"))
                if !trimmedWord.isEmpty {
                    return trimmedWord
                }
            }
        }
        return "Code Generator"
    }

    private static func parseLineDirective(_ line: String) -> (path: String, line: Int)? {
        guard line.hasPrefix("//line ") else { return nil }
        let rest = String(line.dropFirst("//line ".count)).trimmingCharacters(in: .whitespaces)
        guard !rest.isEmpty, let lastColon = rest.lastIndex(of: ":") else { return nil }
        let afterLast = String(rest[rest.index(after: lastColon)...])
        guard let lastNum = Int(afterLast), lastNum >= 1 else { return nil }
        let beforeLast = String(rest[..<lastColon])
        if let secondColon = beforeLast.lastIndex(of: ":") {
            let mid = String(beforeLast[beforeLast.index(after: secondColon)...])
            if let lineNum = Int(mid), lineNum >= 1 {
                let pathPart = String(beforeLast[..<secondColon]).trimmingCharacters(in: .whitespaces)
                if !pathPart.isEmpty {
                    return (pathPart, lineNum)
                }
            }
        }
        let pathPart = beforeLast.trimmingCharacters(in: .whitespaces)
        guard !pathPart.isEmpty else { return nil }
        return (pathPart, lastNum)
    }

    private static func firstLineDirectiveLocation(
        in content: String,
        goDir: String,
        workspaceRoot: String,
        fileExists: (String) -> Bool
    ) -> (path: String, line: Int)? {
        for rawLine in content.split(separator: "\n", omittingEmptySubsequences: false) {
            let line = rawLine.trimmingCharacters(in: CharacterSet(charactersIn: "\r"))
            if let parsed = parseLineDirective(line) {
                let resolved = resolveCandidatePath(
                    parsed.path,
                    goDir: goDir,
                    workspaceRoot: workspaceRoot,
                    fileExists: fileExists
                ) ?? normalizeJoinedPath(base: goDir, relative: parsed.path)
                return (resolved, parsed.line)
            }
        }
        return nil
    }

    private static func extractCommentSourceHint(from lines: [String]) -> String? {
        for raw in lines {
            let trimmed = raw.trimmingCharacters(in: .whitespaces)
            guard trimmed.hasPrefix("//") else { continue }
            let body = String(trimmed.dropFirst(2)).trimmingCharacters(in: .whitespaces)
            let lower = body.lowercased()
            if lower.hasPrefix("source:") {
                var value = String(body.dropFirst("source:".count)).trimmingCharacters(in: .whitespaces)
                if let parenRange = value.range(of: " (") {
                    value = String(value[..<parenRange.lowerBound]).trimmingCharacters(in: .whitespaces)
                }
                if !value.isEmpty && value != "<unspecified>" {
                    return value
                }
            }
        }
        return nil
    }

    private static func extractFlagValue(_ flag: String, from text: String) -> String? {
        let tokens = splitCommandTokens(text)
        for (idx, token) in tokens.enumerated() {
            if token == flag && idx + 1 < tokens.count {
                let next = tokens[idx + 1]
                return next.isEmpty ? nil : next
            }
            if token.hasPrefix(flag + "=") {
                let val = String(token.dropFirst(flag.count + 1))
                return val.isEmpty ? nil : val
            }
        }
        return nil
    }

    private static func extractOapiSpecArg(from command: String) -> String? {
        let tokens = splitCommandTokens(command)
        let specExts = [".yaml", ".yml", ".json"]
        var candidates: [String] = []
        var skipNext = false
        for (idx, token) in tokens.enumerated() {
            if skipNext {
                skipNext = false
                continue
            }
            if token == "-config" || token == "--config" || token == "-o" || token == "--o" || token == "-package" {
                if idx + 1 < tokens.count && token == "-config" {
                    candidates.append(tokens[idx + 1])
                }
                skipNext = true
                continue
            }
            if token.hasPrefix("-config=") || token.hasPrefix("--config=") {
                let eq = token.firstIndex(of: "=")!
                candidates.append(String(token[token.index(after: eq)...]))
                continue
            }
            if !token.hasPrefix("-") && specExts.contains(where: { token.lowercased().hasSuffix($0) }) {
                return token
            }
        }
        return candidates.first
    }

    private static func splitCommandTokens(_ text: String) -> [String] {
        var result: [String] = []
        var current = ""
        var quote: Character? = nil
        for ch in text {
            if let activeQuote = quote {
                if ch == activeQuote {
                    quote = nil
                } else {
                    current.append(ch)
                }
            } else if ch == "\"" || ch == "'" {
                quote = ch
            } else if ch == " " || ch == "\t" || ch == ";" {
                if !current.isEmpty {
                    result.append(current)
                    current = ""
                }
            } else {
                current.append(ch)
            }
        }
        if !current.isEmpty {
            result.append(current)
        }
        return result
    }

    private static func collectGenerateDirectives(
        inDirectory goDir: String,
        excludingFile: String,
        workspaceRoot: String,
        listDirectory: (String) -> [String],
        readFile: (String) -> String?
    ) -> [GoGenerateDirectiveMatch] {
        var dirs = [goDir]
        let parent = (goDir as NSString).deletingLastPathComponent
        if !parent.isEmpty && parent != goDir && (workspaceRoot.isEmpty || isInside(parent, root: workspaceRoot)) {
            dirs.append(parent)
        }
        if !workspaceRoot.isEmpty && !dirs.contains(workspaceRoot) {
            dirs.append(workspaceRoot)
        }

        var found: [GoGenerateDirectiveMatch] = []
        var seenFiles = Set<String>()
        for dir in dirs {
            let entries = listDirectory(dir).sorted()
            for entry in entries where entry.hasSuffix(".go") {
                let full = (dir as NSString).appendingPathComponent(entry)
                guard full != excludingFile, seenFiles.insert(full).inserted,
                      let text = readFile(full) else { continue }
                let lines = text.split(separator: "\n", omittingEmptySubsequences: false)
                for (index, rawLine) in lines.enumerated() {
                    let trimmed = rawLine.trimmingCharacters(in: CharacterSet(charactersIn: "\r \t"))
                    if trimmed.hasPrefix("//go:generate ") {
                        let cmd = String(trimmed.dropFirst("//go:generate ".count)).trimmingCharacters(in: .whitespaces)
                        if !cmd.isEmpty {
                            found.append(GoGenerateDirectiveMatch(filePath: full, line: index + 1, command: cmd))
                        }
                    }
                }
            }
        }
        return found
    }

    private static func pickMatchingDirective(
        generator: String,
        generatedFileName: String,
        headerLine: String,
        candidates: [GoGenerateDirectiveMatch]
    ) -> GoGenerateDirectiveMatch? {
        guard !candidates.isEmpty else { return nil }
        let stem = (generatedFileName as NSString).deletingPathExtension
        let typeFlag = extractFlagValue("-type", from: headerLine)
        let needle: String
        switch generator {
        case "protoc-gen-go", "protoc-gen-go-grpc":
            needle = "protoc"
        case "Code Generator":
            needle = ""
        default:
            needle = generator.lowercased()
        }

        if let typeFlag {
            if let exact = candidates.first(where: { $0.command.contains(typeFlag) }) {
                return exact
            }
        }
        if let byFile = candidates.first(where: { $0.command.contains(generatedFileName) || (!stem.isEmpty && $0.command.contains(stem)) }) {
            return byFile
        }
        if !needle.isEmpty {
            if let byTool = candidates.first(where: { $0.command.lowercased().contains(needle) }) {
                return byTool
            }
        }
        return nil
    }

    private static func inferredStringerTypeName(fromFileName fileName: String) -> String? {
        guard fileName.hasSuffix("_string.go") else { return nil }
        let raw = String(fileName.dropLast("_string.go".count))
        guard !raw.isEmpty else { return nil }
        let parts = raw.split(separator: "_")
        return parts.map { part in
            guard let first = part.first else { return "" }
            return String(first).uppercased() + part.dropFirst()
        }.joined()
    }

    private static func inferredMockgenInterfaceName(in content: String) -> String? {
        for raw in content.split(separator: "\n", omittingEmptySubsequences: false) {
            let line = raw.trimmingCharacters(in: .whitespaces)
            if line.hasPrefix("type Mock") && line.contains(" struct") {
                let after = String(line.dropFirst("type Mock".count))
                if let name = after.split(whereSeparator: { $0 == " " || $0 == "{" || $0 == "[" }).first {
                    return String(name)
                }
            }
        }
        return nil
    }

    private static func findTypeDeclaration(
        named typeName: String,
        inDirectory dir: String,
        excludingFile: String,
        listDirectory: (String) -> [String],
        readFile: (String) -> String?
    ) -> (path: String, line: Int)? {
        for entry in listDirectory(dir).sorted() where entry.hasSuffix(".go") && !entry.hasSuffix("_test.go") {
            let full = (dir as NSString).appendingPathComponent(entry)
            guard full != excludingFile, let text = readFile(full), parseHeader(text) == nil else { continue }
            let lines = text.split(separator: "\n", omittingEmptySubsequences: false)
            for (index, raw) in lines.enumerated() {
                let trimmed = raw.trimmingCharacters(in: .whitespaces)
                if trimmed.hasPrefix("type \(typeName) ") || trimmed.hasPrefix("type \(typeName)=") || trimmed.hasPrefix("type \(typeName)[") {
                    return (full, index + 1)
                }
            }
        }
        return nil
    }

    private static func findInterfaceDeclaration(
        named ifaceName: String,
        inDirectory dir: String,
        excludingFile: String,
        listDirectory: (String) -> [String],
        readFile: (String) -> String?
    ) -> (path: String, line: Int)? {
        for entry in listDirectory(dir).sorted() where entry.hasSuffix(".go") && !entry.hasSuffix("_test.go") {
            let full = (dir as NSString).appendingPathComponent(entry)
            guard full != excludingFile, let text = readFile(full), parseHeader(text) == nil else { continue }
            let lines = text.split(separator: "\n", omittingEmptySubsequences: false)
            for (index, raw) in lines.enumerated() {
                let trimmed = raw.trimmingCharacters(in: .whitespaces)
                if trimmed.hasPrefix("type \(ifaceName) ") && trimmed.contains("interface") {
                    return (full, index + 1)
                }
            }
        }
        return nil
    }

    private static func resolveCandidatePath(
        _ rawPath: String,
        goDir: String,
        workspaceRoot: String,
        fileExists: (String) -> Bool
    ) -> String? {
        let trimmed = rawPath.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return nil }
        if (trimmed as NSString).isAbsolutePath {
            return fileExists(trimmed) ? URL(fileURLWithPath: trimmed).standardizedFileURL.path : nil
        }

        var directCandidates: [String] = [
            normalizeJoinedPath(base: goDir, relative: trimmed)
        ]
        if !workspaceRoot.isEmpty {
            directCandidates.append(normalizeJoinedPath(base: workspaceRoot, relative: trimmed))
        }
        var walk = goDir
        while !walk.isEmpty && walk != "/" {
            directCandidates.append(normalizeJoinedPath(base: walk, relative: trimmed))
            if !workspaceRoot.isEmpty && walk == workspaceRoot { break }
            let next = (walk as NSString).deletingLastPathComponent
            if next == walk { break }
            walk = next
        }
        for candidate in directCandidates where fileExists(candidate) {
            return candidate
        }
        if !workspaceRoot.isEmpty {
            for sub in ["proto", "protos", "api", "sql", "queries", "db"] {
                let nested = normalizeJoinedPath(base: (workspaceRoot as NSString).appendingPathComponent(sub), relative: trimmed)
                if fileExists(nested) {
                    return nested
                }
            }
        }
        let baseName = (trimmed as NSString).lastPathComponent
        if baseName != trimmed {
            let inGoDir = normalizeJoinedPath(base: goDir, relative: baseName)
            if fileExists(inGoDir) { return inGoDir }
            if !workspaceRoot.isEmpty {
                for sub in ["proto", "protos", "api", "sql", "queries", "db"] {
                    let nested = normalizeJoinedPath(base: (workspaceRoot as NSString).appendingPathComponent(sub), relative: baseName)
                    if fileExists(nested) { return nested }
                }
            }
        }
        return nil
    }

    private static func searchAncestorAndSubdirs(
        named fileName: String,
        subdirs: [String],
        startDir: String,
        workspaceRoot: String,
        fileExists: (String) -> Bool
    ) -> String? {
        let direct = normalizeJoinedPath(base: startDir, relative: fileName)
        if fileExists(direct) { return direct }

        var walk = startDir
        while !walk.isEmpty && walk != "/" {
            let here = normalizeJoinedPath(base: walk, relative: fileName)
            if fileExists(here) { return here }
            for sub in subdirs {
                let candidate = normalizeJoinedPath(base: (walk as NSString).appendingPathComponent(sub), relative: fileName)
                if fileExists(candidate) { return candidate }
            }
            if !workspaceRoot.isEmpty && walk == workspaceRoot { break }
            let next = (walk as NSString).deletingLastPathComponent
            if next == walk { break }
            walk = next
        }
        return nil
    }

    private static func searchAncestorNamedDirectory(
        _ dirName: String,
        startDir: String,
        workspaceRoot: String,
        fileExists: (String) -> Bool
    ) -> String? {
        var walk = startDir
        while !walk.isEmpty && walk != "/" {
            let candidate = normalizeJoinedPath(base: walk, relative: dirName)
            if fileExists(candidate) { return candidate }
            if !workspaceRoot.isEmpty && walk == workspaceRoot { break }
            let next = (walk as NSString).deletingLastPathComponent
            if next == walk { break }
            walk = next
        }
        return nil
    }

    private static func findSqlcConfig(
        startDir: String,
        workspaceRoot: String,
        fileExists: (String) -> Bool
    ) -> String? {
        for name in ["sqlc.yaml", "sqlc.yml", "sqlc.json"] {
            if let found = searchAncestorAndSubdirs(
                named: name,
                subdirs: ["db", "sql"],
                startDir: startDir,
                workspaceRoot: workspaceRoot,
                fileExists: fileExists
            ) {
                return found
            }
        }
        return nil
    }

    private static func normalizeJoinedPath(base: String, relative: String) -> String {
        URL(fileURLWithPath: base).appendingPathComponent(relative).standardizedFileURL.path
    }

    private static func isInside(_ path: String, root: String) -> Bool {
        let cleanPath = URL(fileURLWithPath: path).standardizedFileURL.path
        let cleanRoot = URL(fileURLWithPath: root).standardizedFileURL.path
        return cleanPath == cleanRoot || cleanPath.hasPrefix(cleanRoot.hasSuffix("/") ? cleanRoot : cleanRoot + "/")
    }

    private static func uniqueNonEmpty(_ items: [String?]) -> [String] {
        var seen = Set<String>()
        var out: [String] = []
        for item in items {
            guard let item, !item.isEmpty, seen.insert(item).inserted else { continue }
            out.append(item)
        }
        return out
    }

    private static func displayPath(for path: String, workspaceRoot: String) -> String {
        if !workspaceRoot.isEmpty {
            let root = workspaceRoot.hasSuffix("/") ? workspaceRoot : workspaceRoot + "/"
            if path.hasPrefix(root) {
                return String(path.dropFirst(root.count))
            }
        }
        return (path as NSString).lastPathComponent
    }
