package sqlc

import (
	"bytes"
	"encoding/json"
	"go/ast"
	"go/parser"
	"go/token"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"unicode/utf16"
)

type Location struct {
	Path string `json:"path"`
	Line int    `json:"line"`
	Col  int    `json:"col"`
}

type Query struct {
	Name    string    `json:"name"`
	Cmd     string    `json:"cmd"`
	Line    int       `json:"line"`
	NameCol int       `json:"nameCol"`
	EndLine int       `json:"endLine"`
	Go      *Location `json:"go"`
}

type FileResult struct {
	ConfigDir      string   `json:"configDir"`
	GeneratedFiles []string `json:"generatedFiles"`
	Queries        []Query  `json:"queries"`
}

type GoResult struct {
	Name      string     `json:"name"`
	Locations []Location `json:"locations"`
}

const generatedMarker = "// Code generated by sqlc. DO NOT EDIT."

const maxWalkEntries = 20000

var (
	queryLine = regexp.MustCompile(`^\s*(?:--|/\*|#)\s*name:\s*([A-Za-z_][A-Za-z0-9_]*)\s+(:[A-Za-z]+)`)
	skipDirs  = map[string]bool{".git": true, "node_modules": true, "vendor": true, ".build": true}
)

type source struct {
	overlays map[string]string
}

func newSource(overlaysJSON string) source {
	s := source{overlays: map[string]string{}}
	if overlaysJSON != "" {
		_ = json.Unmarshal([]byte(overlaysJSON), &s.overlays)
	}
	return s
}

func (s source) read(path string) ([]byte, error) {
	if text, ok := s.overlays[path]; ok {
		return []byte(text), nil
	}
	return os.ReadFile(path)
}

func (s source) head(path string) []byte {
	if text, ok := s.overlays[path]; ok {
		if len(text) > 512 {
			text = text[:512]
		}
		return []byte(text)
	}
	f, err := os.Open(path)
	if err != nil {
		return nil
	}
	defer f.Close()
	buf := make([]byte, 512)
	n, _ := io.ReadFull(f, buf)
	return buf[:n]
}

func generatedSource(head []byte) (string, bool) {
	if !bytes.Contains(head, []byte(generatedMarker)) {
		return "", false
	}
	for _, line := range strings.Split(string(head), "\n") {
		if rest, ok := strings.CutPrefix(strings.TrimSpace(line), "// source:"); ok {
			return strings.TrimSpace(rest), true
		}
	}
	return "", true
}

type genFile struct {
	path   string
	source string
}

func (s source) walk(root string) (sqlFiles []string, gens []genFile) {
	seen := 0
	if !strings.HasSuffix(root, string(filepath.Separator)) {
		root += string(filepath.Separator)
	}
	_ = filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		if seen++; seen > maxWalkEntries {
			return fs.SkipAll
		}
		if d.IsDir() {
			if path != root && skipDirs[d.Name()] {
				return fs.SkipDir
			}
			return nil
		}
		switch strings.ToLower(filepath.Ext(path)) {
		case ".sql":
			sqlFiles = append(sqlFiles, path)
		case ".go":
			if src, ok := generatedSource(s.head(path)); ok {
				gens = append(gens, genFile{path: path, source: src})
			}
		}
		return nil
	})
	return sqlFiles, gens
}

func matchesSource(path, src string) bool {
	if src == "" {
		return false
	}
	path, src = filepath.ToSlash(path), filepath.ToSlash(src)
	return path == src || strings.HasSuffix(path, "/"+strings.TrimPrefix(src, "./"))
}

func utf16Col(line string, byteCol int) int {
	if byteCol > len(line) {
		byteCol = len(line)
	}
	return len(utf16.Encode([]rune(line[:byteCol]))) + 1
}

func parseQueries(text string) []Query {
	lines := strings.Split(text, "\n")
	var out []Query
	for i, line := range lines {
		m := queryLine.FindStringSubmatchIndex(line)
		if m == nil {
			continue
		}
		if n := len(out); n > 0 {
			out[n-1].EndLine = i
		}
		out = append(out, Query{
			Name:    line[m[2]:m[3]],
			Cmd:     line[m[4]:m[5]],
			Line:    i + 1,
			NameCol: utf16Col(line, m[2]),
		})
	}
	if n := len(out); n > 0 {
		out[n-1].EndLine = len(lines)
	}
	return out
}

func receiverIsQueries(fn *ast.FuncDecl) bool {
	if fn.Recv == nil || len(fn.Recv.List) != 1 {
		return false
	}
	star, ok := fn.Recv.List[0].Type.(*ast.StarExpr)
	if !ok {
		return false
	}
	id, ok := star.X.(*ast.Ident)
	return ok && id.Name == "Queries"
}

type goDecl struct {
	name  string
	line  int
	col   int
	iface bool
}

func decls(src []byte) []goDecl {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "", src, parser.SkipObjectResolution)
	if err != nil {
		return nil
	}
	lines := strings.Split(string(src), "\n")
	at := func(id *ast.Ident, iface bool) (goDecl, bool) {
		p := fset.PositionFor(id.Pos(), false)
		if p.Line < 1 || p.Line > len(lines) {
			return goDecl{}, false
		}
		col := p.Column - 1
		if col < 0 {
			col = 0
		}
		return goDecl{name: id.Name, line: p.Line, col: utf16Col(lines[p.Line-1], col), iface: iface}, true
	}
	var out []goDecl
	for _, d := range file.Decls {
		switch d := d.(type) {
		case *ast.FuncDecl:
			if receiverIsQueries(d) {
				if decl, ok := at(d.Name, false); ok {
					out = append(out, decl)
				}
			}
		case *ast.GenDecl:
			for _, spec := range d.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok || ts.Name.Name != "Querier" {
					continue
				}
				it, ok := ts.Type.(*ast.InterfaceType)
				if !ok {
					continue
				}
				for _, f := range it.Methods.List {
					if _, isFunc := f.Type.(*ast.FuncType); isFunc && len(f.Names) == 1 {
						if decl, ok := at(f.Names[0], true); ok {
							out = append(out, decl)
						}
					}
				}
			}
		}
	}
	return out
}

func QueryForGo(genPath string, line int, root, overlaysJSON string) GoResult {
	s := newSource(overlaysJSON)
	res := GoResult{Locations: []Location{}}
	if !within(resolve(genPath), resolve(root)) {
		return res
	}
	src, ok := generatedSource(s.head(genPath))
	if !ok {
		return res
	}
	text, err := s.read(genPath)
	if err != nil {
		return res
	}
	for _, d := range decls(text) {
		if d.line == line {
			res.Name = d.name
		}
	}
	if res.Name == "" {
		return res
	}
	sqlFiles, _ := s.walk(root)
	var all, preferred []Location
	for _, p := range sqlFiles {
		body, err := s.read(p)
		if err != nil {
			continue
		}
		for _, q := range parseQueries(string(body)) {
			if q.Name != res.Name {
				continue
			}
			loc := Location{Path: p, Line: q.Line, Col: q.NameCol}
			all = append(all, loc)
			if matchesSource(p, src) {
				preferred = append(preferred, loc)
			}
		}
	}
	if len(preferred) > 0 {
		all = preferred
	}
	if all != nil {
		res.Locations = nearest(genPath, all)
	}
	return res
}

func dirParts(p string) []string {
	return strings.Split(filepath.ToSlash(filepath.Dir(p)), "/")
}

func closeness(a, b string) (depth, names int) {
	pa, pb := dirParts(a), dirParts(b)
	for depth < len(pa) && depth < len(pb) && pa[depth] == pb[depth] {
		depth++
	}
	rest := map[string]bool{}
	for _, n := range pb[depth:] {
		rest[n] = true
	}
	for _, n := range pa[depth:] {
		if rest[n] {
			names++
		}
	}
	return depth, names
}

func nearest(from string, locs []Location) []Location {
	bestDepth, bestNames, out := -1, -1, []Location{}
	for _, l := range locs {
		d, n := closeness(from, l.Path)
		switch {
		case d > bestDepth || d == bestDepth && n > bestNames:
			bestDepth, bestNames, out = d, n, []Location{l}
		case d == bestDepth && n == bestNames:
			out = append(out, l)
		}
	}
	return out
}

func resolve(p string) string {
	p = filepath.Clean(p)
	var tail []string
	for {
		if r, err := filepath.EvalSymlinks(p); err == nil {
			for i := len(tail) - 1; i >= 0; i-- {
				r = filepath.Join(r, tail[i])
			}
			return r
		}
		parent := filepath.Dir(p)
		if parent == p {
			for i := len(tail) - 1; i >= 0; i-- {
				p = filepath.Join(p, tail[i])
			}
			return p
		}
		tail = append(tail, filepath.Base(p))
		p = parent
	}
}

func within(path, root string) bool {
	if root == string(filepath.Separator) {
		return strings.HasPrefix(path, root)
	}
	return path == root || strings.HasPrefix(path, root+string(filepath.Separator))
}

func configDir(sqlPath, root string) string {
	resRoot := resolve(root)
	hasRoot := root != "" && root != "."
	for dir := filepath.Dir(sqlPath); ; dir = filepath.Dir(dir) {
		resDir := resolve(dir)
		if hasRoot && !within(resDir, resRoot) {
			return ""
		}
		for _, name := range []string{"sqlc.yaml", "sqlc.yml", "sqlc.json"} {
			if _, err := os.Stat(filepath.Join(dir, name)); err == nil {
				return dir
			}
		}
		if (hasRoot && resDir == resRoot) || dir == filepath.Dir(dir) {
			return ""
		}
	}
}

func QueriesInFile(sqlPath, content, root, overlaysJSON string) FileResult {
	s := newSource(overlaysJSON)
	res := FileResult{ConfigDir: configDir(sqlPath, root), GeneratedFiles: []string{}, Queries: parseQueries(content)}
	if res.Queries == nil {
		res.Queries = []Query{}
		return res
	}
	_, gens := s.walk(root)
	byName := map[string][]Location{}
	for _, g := range gens {
		text, err := s.read(g.path)
		if err != nil {
			continue
		}
		matched := matchesSource(sqlPath, g.source)
		if !matched && strings.HasSuffix(g.source, ".sql") {
			continue
		}
		for _, d := range decls(text) {
			if !d.iface {
				byName[d.name] = append(byName[d.name], Location{g.path, d.line, d.col})
			}
		}
	}
	outDirs := map[string]bool{}
	for i, q := range res.Queries {
		if best := nearest(sqlPath, byName[q.Name]); len(best) > 0 {
			res.Queries[i].Go = &best[0]
			outDirs[filepath.Dir(best[0].Path)] = true
		}
	}
	for _, g := range gens {
		if outDirs[filepath.Dir(g.path)] {
			res.GeneratedFiles = append(res.GeneratedFiles, g.path)
		}
	}
	return res
}

func QueryForGoJSON(genPath string, line int, root, overlaysJSON string) string {
	b, _ := json.Marshal(QueryForGo(genPath, line, root, overlaysJSON))
	return string(b)
}

type QueryText struct {
	Name      string `json:"name"`
	Cmd       string `json:"cmd"`
	Line      int    `json:"line"`
	SQL       string `json:"sql"`
	StartByte int    `json:"startByte"`
	EndByte   int    `json:"endByte"`
}

func QueryAt(content string, line int) (QueryText, bool) {
	for _, q := range parseQueries(content) {
		if line < q.Line || line > q.EndLine {
			continue
		}
		starts := []int{0}
		for i := 0; i < len(content); i++ {
			if content[i] == '\n' {
				starts = append(starts, i+1)
			}
		}
		start, end := len(content), len(content)
		if q.Line < len(starts) {
			start = starts[q.Line]
		}
		if q.EndLine < len(starts) {
			end = starts[q.EndLine]
		}
		for start < end && strings.IndexByte(" \t\r\n", content[start]) >= 0 {
			start++
		}
		for end > start && strings.IndexByte(" \t\r\n", content[end-1]) >= 0 {
			end--
		}
		return QueryText{Name: q.Name, Cmd: q.Cmd, Line: q.Line, SQL: content[start:end], StartByte: start, EndByte: end}, true
	}
	return QueryText{}, false
}

func ConfigDir(sqlPath, root string) string {
	return configDir(sqlPath, root)
}

func QueriesInFileJSON(sqlPath, content, root, overlaysJSON string) string {
	b, _ := json.Marshal(QueriesInFile(sqlPath, content, root, overlaysJSON))
	return string(b)
}
