func TestRunPackageAnalyzersJSON_CategoriesZeroBasedLinesAndCleanFiles(t *testing.T) {
	pkgDir := t.TempDir()

	dirtyFile := filepath.Join(pkgDir, "service.go")
	dirtySrc := `package sample

import (
	"context"
	"crypto/md5"
	"errors"
	"fmt"
	"net/http"
)

var ErrNotFound = errors.New("not found")

type Account struct {
	Password string
}

func Run(parent context.Context, url string, payload interface{}) error {
	ctx, _ := context.WithCancel(parent)
	_ = ctx
	resp, err := http.Get(url)
	if err == ErrNotFound {
		return fmt.Errorf("fetch failed: %v", err)
	}
	_ = resp
	_ = md5.New()
	_ = payload
	return nil
}
`
	cleanFile := filepath.Join(pkgDir, "clean.go")
	cleanSrc := `package sample

func Add(a, b int) int {
	return a + b
}
`
	genFile := filepath.Join(pkgDir, "generated.pb.go")
	genSrc := `// Code generated by protoc-gen-go. DO NOT EDIT.

package sample

type GeneratedSecret struct {
	Password string
	Data     interface{}
}
`

	if err := os.WriteFile(dirtyFile, []byte(dirtySrc), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(cleanFile, []byte(cleanSrc), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(genFile, []byte(genSrc), 0o644); err != nil {
		t.Fatal(err)
	}

	raw := RunPackageAnalyzersJSON(pkgDir, pkgDir, "")
	var out PackageAnalyzeResult
	if err := json.Unmarshal([]byte(raw), &out); err != nil {
		t.Fatalf("unmarshal failed: %v\njson=%s", err, raw)
	}
	if out.Status != "ok" {
		t.Fatalf("expected status ok, got %q (%s)", out.Status, out.Error)
	}

	cleanDiags, hasClean := out.Files[cleanFile]
	if !hasClean || cleanDiags == nil || len(cleanDiags) != 0 {
		t.Fatalf("expected clean file present with empty slice [], got present=%v diags=%v", hasClean, cleanDiags)
	}
	if !strings.Contains(raw, `"clean.go":[]`) && !strings.Contains(raw, filepath.Base(cleanFile)+`":[]`) {
		t.Fatalf("expected JSON empty array [] for clean file, got %s", raw)
	}

	genDiags, hasGen := out.Files[genFile]
	if !hasGen || len(genDiags) != 0 {
		t.Fatalf("expected generated file skipped with empty slice, got present=%v diags=%v", hasGen, genDiags)
	}

	diags := out.Files[dirtyFile]
	if len(diags) == 0 {
		t.Fatalf("expected diagnostics for dirty file, got none")
	}

	codes := map[string]bool{}
	foundZeroBasedPassword := false
	for _, d := range diags {
		codes[d.Code] = true
		if d.Source != "golens-safety" {
			t.Fatalf("expected source golens-safety, got %q", d.Source)
		}
		if d.Line < 0 {
			t.Fatalf("expected 0-based non-negative line, got %d", d.Line)
		}
		if d.Line == 13 && d.Code == CategorySecurity {
			foundZeroBasedPassword = true
		}
	}
	if !foundZeroBasedPassword {
		t.Fatalf("expected 0-based line 13 (1-based line 14) for Password field, got %+v", diags)
	}
	for _, want := range []string{
		CategoryConcurrency,
		CategoryResourceSafety,
		CategoryErrorHandling,
		CategorySecurity,
	} {
		if !codes[want] {
			t.Errorf("expected diagnostic in category %q, got categories %v (diags=%+v)", want, codes, diags)
		}
	}
	if codes[CategoryModernization] {
		t.Errorf("expected background %q diagnostics deduplicated with gopls, got categories %v (diags=%+v)", CategoryModernization, codes, diags)
	}

	filteredRaw := RunPackageAnalyzersJSON(pkgDir, pkgDir, "resourceSafety,security")
	var filtered PackageAnalyzeResult
	if err := json.Unmarshal([]byte(filteredRaw), &filtered); err != nil {
		t.Fatal(err)
	}
	for _, d := range filtered.Files[dirtyFile] {
		if d.Code == CategoryResourceSafety || d.Code == CategorySecurity {
			t.Fatalf("disabled category %q was still reported: %+v", d.Code, d)
		}
	}
}

func TestRunPackageAnalyzersJSON_OverlayClearsFixedFileAndUnder20ms(t *testing.T) {
	pkgDir := t.TempDir()
	file := filepath.Join(pkgDir, "handler.go")
	diskSrc := `package handler

type Credentials struct {
	APIKey string
}

func Identity(v interface{}) interface{} {
	return v
}
`
	if err := os.WriteFile(file, []byte(diskSrc), 0o644); err != nil {
		t.Fatal(err)
	}

	for i := 0; i < 6; i++ {
		extra := filepath.Join(pkgDir, "helper_"+string(rune('a'+i))+".go")
		src := "package handler\n\nfunc Helper" + string(rune('A'+i)) + "(x int) int { return x + 1 }\n"
		if err := os.WriteFile(extra, []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}

	prevOverlay := OverlayReader
	defer func() { OverlayReader = prevOverlay }()

	OverlayReader = func(path string) ([]byte, error) {
		if path == file {
			return []byte("package handler\n\ntype Credentials struct {\n\tAPIKey string `json:\"-\"`\n}\n\nfunc Identity(v any) any {\n\treturn v\n}\n"), nil
		}
		return nil, os.ErrNotExist
	}

	start := time.Now()
	raw := RunPackageAnalyzersJSON(pkgDir, pkgDir, "")
	elapsed := time.Since(start)
	if elapsed > 20*time.Millisecond {
		t.Fatalf("expected package analysis <20ms, took %v", elapsed)
	}

	var res PackageAnalyzeResult
	if err := json.Unmarshal([]byte(raw), &res); err != nil {
		t.Fatal(err)
	}
	diags, ok := res.Files[file]
	if !ok {
		t.Fatalf("expected %s in Files map", file)
	}
	if len(diags) != 0 {
		t.Fatalf("expected overlay fix to clear diagnostics to [], got %+v", diags)
	}
}

func TestContextualASTQuickFixes_SensitiveAndModernize(t *testing.T) {
	src := "package demo\n\ntype Config struct {\n\tSecretToken string\n}\n\nfunc Wrap(x interface{}) interface{} {\n\treturn x\n}\n"

	sensFixes, err := ContextualASTQuickFixes("", "demo.go", src, 4)
	if err != nil {
		t.Fatal(err)
	}
	foundSens := false
	for _, fx := range sensFixes {
		if strings.Contains(fx.UpdatedSource, `json:"-"`) {
			foundSens = true
		}
	}
	if !foundSens {
		t.Fatalf("expected sensitive json:\"-\" quick fix on line 4, got %+v", sensFixes)
	}

	modFixes, err := ContextualASTQuickFixes("", "demo.go", src, 7)
	if err != nil {
		t.Fatal(err)
	}
	foundMod := false
	for _, fx := range modFixes {
		if strings.Contains(fx.UpdatedSource, "func Wrap(x any)") {
			foundMod = true
		}
	}
	if !foundMod {
		t.Fatalf("expected interface{} -> any quick fix on line 7, got %+v", modFixes)
	}
}
