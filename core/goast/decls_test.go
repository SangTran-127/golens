package goast

import (
	"reflect"
	"testing"
)

func TestDeclarationsUseNamePositions(t *testing.T) {
	src := "package p\n\ntype Server struct{}\n\nfunc (s *Server) Serve() error { return nil }\n\nfunc Map[T any](xs []T) []T { return xs }\n\ntype ID int\n\ntype Alias = string\n\ntype (\n\tGrouped struct{}\n\tReader  interface{ Read() }\n)\n\nfunc (l *List[T]) Push(v T) {}\n\n/* \U0001F600 */ func Wide() {}\n"
	want := []Decl{
		{"Server", "type", 3, 6},
		{"Serve", "method", 5, 18},
		{"Map", "func", 7, 6},
		{"ID", "type", 9, 6},
		{"Alias", "type", 11, 6},
		{"Grouped", "type", 14, 2},
		{"Reader", "interface", 15, 2},
		{"Push", "method", 18, 19},
		{"Wide", "func", 20, 15}, // "/* " + emoji (two UTF-16 units) + " */ func "
	}
	if got := Declarations([]byte(src)); !reflect.DeepEqual(got, want) {
		t.Fatalf("got  %v\nwant %v", got, want)
	}
}

func TestDeclarationsSurviveSyntaxErrors(t *testing.T) {
	got := Declarations([]byte("package p\n\nfunc A() {}\n\nfunc B( {\n"))
	if len(got) == 0 || got[0].Name != "A" {
		t.Fatalf("got %v", got)
	}
}

func TestDeclarationsWithLineDirectiveWithoutColumn(t *testing.T) {
	src := "// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage gen\n\n//line ../api/greet.proto:4\nfunc Greet() {}\n"
	got := Declarations([]byte(src))
	want := []Decl{{"Greet", "func", 6, 6}}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("got %v, want %v", got, want)
	}
}
